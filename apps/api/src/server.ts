import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import {cities} from './modules/cities/catalog.js';
const app=express();
const port=Number(process.env.PORT||3001);
app.disable('x-powered-by');
app.use(cors({origin:process.env.WEB_ORIGIN||'http://localhost:5173'}));
app.use(express.json({limit:'200kb'}));
app.get('/health',(_req,res)=>res.json({status:'ok',service:'kindhop-api'}));
app.get('/api/cities',(_req,res)=>res.json({cities}));
app.get('/api/cities/:cityId',(req,res)=>{const city=cities.find(c=>c.id===req.params.cityId);if(!city){res.status(404).json({error:{code:'CITY_NOT_FOUND',message:'Ciudad no disponible'}});return;}res.json({city});});
app.use((_req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'Ruta no encontrada'}}));
app.listen(port,()=>console.log(`KindHop API listening on http://localhost:${port}`));
